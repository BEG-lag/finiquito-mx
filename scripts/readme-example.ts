/**
 * Generates the worked example shown in README.md and README.es.md from the
 * library itself, so every number in the docs comes from running the code.
 *
 *   node scripts/readme-example.ts           print both blocks
 *   node scripts/readme-example.ts --write   rewrite the blocks in the READMEs
 *
 * test/readme.test.ts fails if the READMEs drift from this output.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { calculateSeverance, type Locale, type SeveranceInput } from '../src/index.ts';

export const README_EXAMPLE_INPUT: SeveranceInput = {
  startDate: '2019-03-01',
  endDate: '2026-10-31',
  salary: { amount: '25000', period: 'monthly' },
  reason: 'unjustified-dismissal',
  options: { litigationMonths: 18 },
};

const HEAD: Record<Locale, string[]> = {
  en: ['Item', 'Formula', 'Legal basis', 'Amount'],
  es: ['Concepto', 'Fórmula', 'Fundamento', 'Importe'],
};

const TEXT = {
  en: {
    service: 'Service',
    years: 'years',
    days: 'days',
    daily: 'daily salary',
    sdi: 'integrated daily salary (estimated)',
    mw: '2026 general minimum wage',
    total: 'Total (finiquito + liquidación)',
    litigation: 'With the 18-month litigation scenario (estimate)',
    tax: 'ISR-exempt portions (LISR art. 93, UMA 2026 of',
    taxRows: (a: string, p: string, s: string, y: number) =>
      `aguinaldo ${a} (cap 30 UMA), prima vacacional ${p} (cap 15 UMA), separation pay ${s} (cap 90 UMA × ${y} years). Everything else is taxable.`,
  },
  es: {
    service: 'Antigüedad',
    years: 'años',
    days: 'días',
    daily: 'salario diario',
    sdi: 'salario diario integrado (estimado)',
    mw: 'salario mínimo general 2026',
    total: 'Total (finiquito + liquidación)',
    litigation: 'Con el escenario de 18 meses de juicio (estimación)',
    tax: 'Partes exentas de ISR (LISR art. 93, UMA 2026 de',
    taxRows: (a: string, p: string, s: string, y: number) =>
      `aguinaldo ${a} (tope 30 UMA), prima vacacional ${p} (tope 15 UMA), pagos por separación ${s} (tope 90 UMA × ${y} años). Lo demás está gravado.`,
  },
} as const;

export function exampleMarkdown(locale: Locale): string {
  const r = calculateSeverance(README_EXAMPLE_INPUT, { locale });
  const tx = TEXT[locale];
  const lines: string[] = [];
  lines.push(
    `${tx.service}: ${r.service.completedYears} ${tx.years}, ${r.service.daysIntoCurrentYear} ${tx.days} (${r.service.years}) · ` +
      `${tx.daily} ${r.salary.daily.formatted} · ${tx.sdi} ${r.salary.integrated.formatted} · ` +
      `${tx.mw} ${r.indicators.minimumWage?.daily.formatted ?? ''}`,
  );
  lines.push('');
  lines.push(`| ${HEAD[locale].join(' | ')} |`);
  lines.push('|---|---|---|---:|');
  for (const i of r.items.filter((x) => x.group !== 'litigation')) {
    lines.push(`| ${i.label} | \`${i.formula}\` | ${i.legalBasis.join(', ')} | ${i.amount.formatted} |`);
  }
  lines.push(`| **${tx.total}** | | | **${r.totals.total.formatted}** |`);
  for (const i of r.items.filter((x) => x.group === 'litigation')) {
    lines.push(`| _${i.label}_ | \`${i.formula}\` | ${i.legalBasis.join(', ')} | _${i.amount.formatted}_ |`);
  }
  lines.push(`| _${tx.litigation}_ | | | _${r.totals.totalWithLitigation.formatted}_ |`);
  lines.push('');
  if (r.tax) {
    const exempt = (id: string): string => r.tax?.rows.find((x) => x.id === id)?.exempt.formatted ?? '$0.00';
    lines.push(
      `${tx.tax} ${r.tax.umaDaily.formatted}): ${tx.taxRows(exempt('aguinaldo'), exempt('vacation-premium'), exempt('separation'), r.tax.yearsForExemption)}`,
    );
  }
  return lines.join('\n');
}

const START = '<!-- example:start (generated by scripts/readme-example.ts, do not edit) -->';
const END = '<!-- example:end -->';

export function replaceBlock(doc: string, block: string): string {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error('README is missing the example markers');
  return `${doc.slice(0, a + START.length)}\n${block}\n${doc.slice(b)}`;
}

export function extractBlock(doc: string): string | null {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) return null;
  return doc.slice(a + START.length, b).trim();
}

export const README_FILES: Record<Locale, string> = {
  en: join(resolve(import.meta.dirname, '..'), 'README.md'),
  es: join(resolve(import.meta.dirname, '..'), 'README.es.md'),
};

// `import.meta.main` exists from Node 24; compare paths on older runtimes.
const isMain =
  (import.meta as { main?: boolean }).main ?? resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url);

if (isMain) {
  const write = process.argv.includes('--write');
  for (const locale of ['en', 'es'] as const) {
    const block = exampleMarkdown(locale);
    if (write) {
      const file = README_FILES[locale];
      writeFileSync(file, replaceBlock(readFileSync(file, 'utf8'), block));
      console.log(`updated ${file}`);
    } else {
      console.log(`--- ${locale}\n${block}\n`);
    }
  }
}
